"""
config.py — конфигурация оркестратора Panoptis.

Держи этот файл рядом со скриптами оркестратора. НЕ путай с config.py
скрапера — там свои настройки (Selenium, ЕИС и т.д.).

DOCS_DIR обязан указывать на ту же папку, куда скрапер (downloader.py)
кладёт подпапки закупок docs/<reg_number>/...
"""

from pathlib import Path

# ── Пути ──────────────────────────────────────────────────────────────────

# Папка, куда скрапер кладёт подпапки закупок. Должна совпадать
# с config.DOCS_DIR из конфига скрапера.
DOCS_DIR = Path(r"c:\Panoptis\parsergoszak\docs")

# Файл SQLite базы данных оркестратора
DB_PATH = Path(r"C:\agent\data\panoptis.db")

# Папка для логов оркестратора
LOG_DIR = Path(r"C:\agent\data\logs")

# Имя флага готовности, который пишет скрапер по завершении скачивания
DONE_FLAG_NAME = "_done.flag"

# Расширения, которые оркестратор умеет анализировать в MVP.
# Форматы Word — .docx (нативно), .rtf (striprtf, чистый Python),
# .odt (ручной парсинг content.xml, чистый Python), .doc (старый
# бинарный формат — требует LibreOffice, см. text_extractor.py).
# .pdf и .xls сознательно пока не поддержаны — нужен отдельный
# конвертер/OCR, добавим следующим шагом.
SUPPORTED_EXTENSIONS = {".docx", ".xlsx", ".doc", ".rtf", ".odt"}

# ── LLM (llama.cpp HTTP API) ────────────────────────────────────────────

# Используем низкоуровневый /completion, а не /v1/chat/completions:
# каждый документ — это ОДИН самостоятельный запрос без истории диалога.
# Это не только логично для параллельной обработки разных файлов,
# но и обходит стороной баг с сбоями модели на втором сообщении в чате —
# истории сообщений тут просто нет в принципе.
LLM_URL = "http://127.0.0.1:8080/completion"

LLM_TEMPERATURE = 0.1
LLM_TOP_P = 0.9
LLM_REPEAT_PENALTY = 1.1
LLM_N_PREDICT = 1024          # с запасом под длинные списки позиций (было 256)
LLM_TIMEOUT_SEC = 120

# Максимальная длина текста документа, отправляемого в промпт (в символах).
# При контексте -c 8192 и грубой оценке ~2.5-3 символа/токен для русского
# текста оставляем запас под системную часть промпта и под ответ модели
# (LLM_N_PREDICT). Более длинные документы обрезаются с предупреждением
# в лог — для MVP (5-10 страниц) это редкий случай.
MAX_DOC_CHARS = 12000

# ── Очередь / воркер ────────────────────────────────────────────────────

# Как часто воркер опрашивает БД на предмет новых закупок (секунды)
POLL_INTERVAL_SEC = 10

# Сколько раз повторять запрос к LLM при невалидном JSON в ответе
MAX_JSON_RETRIES = 2
